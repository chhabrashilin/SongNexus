/**
 * City landmarks: one hand-drawn silhouette per major city in the Around you
 * directory (Madison's State Capitol, the Golden Gate, the Eiffel Tower...),
 * drawn for SongNexus on a 64 × 64 grid with the ground at y = 56. Cities
 * without one get a generic skyline. Keys are community ids
 * (server/src/songnexus/catalog/communities.json).
 *
 * A drawing is a few layers, all in the tile's ink color:
 * - `fill`: solid shapes;
 * - `soft`: shapes at reduced opacity (shaded faces, hills, back shells);
 * - `lines`: strokes as [path, width], round caps;
 * - `holes` / `holeLines`: cut out of everything above (windows, arches).
 */

export interface Landmark {
  /** What it shows, for the accessible description. */
  name: string;
  fill?: string[];
  soft?: string[];
  lines?: [string, number][];
  holes?: string[];
  holeLines?: [string, number][];
}

const n = (v: number) => +v.toFixed(2);

/** A rectangle. */
export const R = (x: number, y: number, w: number, h: number) =>
  `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}z`;
/** A circle. */
export const C = (cx: number, cy: number, r: number) =>
  `M${n(cx - r)} ${n(cy)}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0z`;
/** An ellipse. */
const E = (cx: number, cy: number, rx: number, ry: number) =>
  `M${n(cx - rx)} ${n(cy)}a${rx} ${ry} 0 1 0 ${n(2 * rx)} 0a${rx} ${ry} 0 1 0 ${n(-2 * rx)} 0z`;
/** A polygon through x, y pairs. */
export const P = (...pts: number[]) => {
  const xy = (i: number) => `${n(pts[i] ?? 0)} ${n(pts[i + 1] ?? 0)}`;
  let d = `M${xy(0)}`;
  for (let i = 2; i < pts.length; i += 2) d += `L${xy(i)}`;
  return `${d}z`;
};
/** An arched opening: a rectangle with a round top, `w` wide, `h` tall. */
const A = (x: number, y: number, w: number, h: number) =>
  `M${n(x)} ${n(y + h)}V${n(y + w / 2)}a${w / 2} ${w / 2} 0 0 1 ${w} 0V${n(y + h)}z`;
/** An onion dome sitting on (cx, by), `w` wide at the bulge, `h` tall. */
const ON = (cx: number, by: number, w: number, h: number) =>
  `M${n(cx - w * 0.3)} ${by}C${n(cx - w * 0.75)} ${n(by - h * 0.35)} ${n(cx - w * 0.08)} ${n(by - h * 0.62)} ${cx} ${n(by - h)}C${n(cx + w * 0.08)} ${n(by - h * 0.62)} ${n(cx + w * 0.75)} ${n(by - h * 0.35)} ${n(cx + w * 0.3)} ${by}z`;

const range = (count: number, f: (i: number) => string) =>
  Array.from({length: count}, (_, i) => f(i));

/** Five-pointed star centered on (cx, cy). */
const STAR = (cx: number, cy: number, r: number) =>
  P(
    ...Array.from({length: 10}, (_, i) => {
      const a = -Math.PI / 2 + (i * Math.PI) / 5;
      const rr = i % 2 ? r * 0.42 : r;
      return [cx + rr * Math.cos(a), cy + rr * Math.sin(a)];
    }).flat(),
  );

